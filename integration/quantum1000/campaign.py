#!/usr/bin/env python3
"""Experiment orchestration, transport and metrics. Agent algorithms are XI.

One VQC episode is one labelled sample; a QRL episode has multiple decisions.
Test labels and rewards are generated by the separate XI benchmark environment.
"""
import argparse
from datetime import datetime, timezone
import gzip
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import shutil
import statistics
import struct
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
XI = ROOT/'ai/xi/quantum1000'
A = 8140000000000000000
TASKS = {'linear':0, 'parity':1, 'radial':2, 'dense':3}

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def publish_text(path, content):
    """Publish a complete evidence file; never expose a truncated rewrite."""
    path=Path(path)
    pending=path.with_name(path.name+'.pending')
    with pending.open('w') as file:
        file.write(content);file.flush();os.fsync(file.fileno())
    pending.replace(path)

def sample_seed(seed, split, index):
    data = hashlib.sha256(f'BBYQ-V3:{seed}:{split}:{index}'.encode()).digest()
    return int.from_bytes(data[:4], 'little') & 0x7fffffff

def metrics(events):
    return {e['name']:e['value'] for e in events if e.get('type') == 'metric'}

def wilson(successes, total):
    if not total:
        return [0., 1.]
    z = 1.959963984540054
    p = successes/total
    center = (p+z*z/(2*total))/(1+z*z/total)
    half = z*math.sqrt(p*(1-p)/total+z*z/(4*total*total))/(1+z*z/total)
    return [center-half, center+half]

def percentile(values, fraction):
    if not values:
        return None
    v = sorted(values)
    return v[min(len(v)-1, int((len(v)-1)*fraction))]

class Experiment:
    def __init__(self, args):
        self.args = args
        self.runtime = Path(args.runtime).resolve()
        sys.path.insert(0, str(self.runtime/'scripts'))
        from xi_session_client import XiSession
        self.Session = XiSession
        self.binary = Path(args.session_binary).resolve() if args.session_binary else self.runtime/'build/xi_session'
        self.cli = self.runtime/'build/reverse_pc'
        self.joint_mode = getattr(args, 'joint_mode', 'independent')
        if self.joint_mode!='independent' or getattr(args,'analytic',False):
            raise ValueError('Connected campaigns currently validate independent agents; historical integration modes remain in integration/quantum3')
        self.source_names = ['birth.xi','common.xi','benchmarks.xi','qrl3.xi']
        self.lib = '\n'.join((XI/p).read_text() for p in self.source_names if p!='birth.xi')
        self.out = Path(args.output).resolve()
        self.out.mkdir(parents=True, exist_ok=True)
        self.train_seeds = [sample_seed(args.seed, 'train', i) for i in range(args.episodes)]
        eval_seeds = {sample_seed(args.seed, split, i) for split in ['iid', 'ood'] for i in range(args.eval_size)}
        assert not set(self.train_seeds) & eval_seeds, 'train/evaluation RNG seed overlap'
        if len(set(self.train_seeds)) != len(self.train_seeds):
            raise RuntimeError('training seed collision: select another campaign seed')

    def source(self, body):
        budget = f'budget {self.args.step_budget}\n' if self.args.step_budget != 1000000 else ''
        return '#!reverse-pc-machine-v1\n'+budget+body+'\nhalt\n'+self.lib

    def stage(self, split, index, training=False, greedy=False, ablate=False, random=False):
        seed = sample_seed(self.args.seed, split, index)
        baseline = 1 if ablate else 2 if self.args.classical else 0
        lines = [f'store64 {A+256} {seed}', f'store64 {A+280} {baseline}']
        if self.joint_mode!='independent':
            lines.append(f'store64 {A+544} {2 if self.joint_mode=="joint" else 1}')
        if self.args.agent == 'vqc':
            lines += [f'store64 {A+272} {TASKS[self.args.task]}',
                      f'fstore {A+296} {0.6 if split == "ood" else 0.1}',
                      'call vqc_sample', f'store64 {A} 0']
            if training:
                lines += ['call supervised_update']
            elif random:
                lines += ['call random_prediction','femit probability f21']
            else:
                lines += ['call select_agent', 'call forward', 'femit probability f21']
            lines += [f'fload f0 {A+128}', 'femit label f0']
        else:
            mode = 0 if training else 3 if random else 2 if greedy else 1
            lines += [f'fstore {A+304} {0.15 if self.args.task == "line_slip" else 0}',
                      f'store64 {A+312} {12 if self.args.task == "line_slip" else 8}',
                      f'store64 {A+320} {mode}', f'store64 {A+328} {int(split=="ood")}',
                      f'store64 {A+336} {int(split=="ood")}', 'call qrl_episode']
        return '\n'.join(lines)

    def evaluate(self, checkpoint, split='iid', ablate=False, random=False, greedy=False):
        values = []
        elapsed = 0.
        with self.Session(self.binary, checkpoint) as evaluator:
            for i in range(self.args.eval_size):
                source=self.source(self.stage(split, i, ablate=ablate, random=random, greedy=greedy))
                if random and self.args.agent=='vqc':
                    source+='\n'+(XI/'baselines.xi').read_text()
                result, ms = evaluator.execute(source)
                values.append(metrics(result)); elapsed += ms
            usage = evaluator.metrics()
        if self.args.agent == 'vqc':
            correct = sum(int(x['probability']>=.5)==int(x['label']) for x in values)
            result = {'accuracy':correct/len(values), 'correct':correct,
                      'brier':statistics.mean((x['probability']-x['label'])**2 for x in values),
                      'cross_entropy':statistics.mean(-x['label']*math.log(max(x['probability'],1e-12))-
                          (1-x['label'])*math.log(max(1-x['probability'],1e-12)) for x in values)}
        else:
            correct = sum(int(x['success']) for x in values)
            result = {'success_rate':correct/len(values), 'successes':correct,
                      'mean_reward':statistics.mean(x['reward'] for x in values),
                      'mean_decisions':statistics.mean(x['decisions'] for x in values)}
        result.update({'examples':len(values), 'wilson95':wilson(correct, len(values)),
                       'elapsed_ms':elapsed, 'peak_rss_kib':usage['peak_rss_kib'], 'cpu_ms':usage['cpu_ms']})
        return result

    def model_state(self, session):
        role = 0 if self.args.agent == 'vqc' else 1
        theta = A+(100000 if role==0 else 200000)
        weight = theta+10000
        visits = theta+20000
        meta = A+(4000 if role==0 else 5000)
        source = '\n'.join(f'mem_materialize {address} {size}' for address, size in
                            [(theta,8000),(weight,8000),(visits,8000),(meta,48)])
        events,_ = session.execute(self.source(source))
        packed = [bytes.fromhex(x['hex']) for x in events if x['type']=='memory_materialization']
        angles, weights = [struct.unpack('<1000d', p) for p in packed[:2]]
        counts = struct.unpack('<1000q', packed[2])
        digest = hashlib.sha256(b''.join(packed)).hexdigest()
        return {'parameter_sha256':digest, 'rotation_parameters_updated':sum(x>0 for x in counts),
                'rotation_parameters_changed':sum(abs(x-.31)>1e-12 for x in angles),
                'readout_parameters_changed':sum(abs(x)>1e-12 for x in weights),
                'minimum_rotation_updates':min(counts), 'maximum_rotation_updates':max(counts),
                'training_episodes_in_checkpoint':struct.unpack('<q',packed[3][:8])[0],
                'training_decisions_in_checkpoint':struct.unpack('<q',packed[3][8:16])[0]}

    def run(self):
        args = self.args
        manifest = self.out/'manifest.json'
        if manifest.exists() and not args.resume:
            raise RuntimeError('campaign exists; choose a new output or use --resume')
        sources = {p:sha(XI/p) for p in self.source_names}
        identity = {'agent':args.agent,'task':args.task,'seed':args.seed,'classical':args.classical,
                    'joint_mode':getattr(args,'joint_mode','independent'),
                    'analytic_classical_equivalent':getattr(args,'analytic',False),
                    'runtime_sha256':sha(self.binary),'xi_source_sha256':sources,
                    'step_budget':args.step_budget,
                    'initial_checkpoint_sha256':sha(args.initial_checkpoint) if getattr(args,'initial_checkpoint',None) else None}
        records = []
        training = []
        if args.resume:
            previous = json.loads(manifest.read_text())
            assert previous['identity'] == identity, 'resume requires the identical runtime and XI sources'
            state = self.out/previous['latest_checkpoint']
            assert sha(state) == previous['latest_checkpoint_sha256']
            records = previous['milestones']
            training = [json.loads(l) for l in (self.out/'training.jsonl').read_text().splitlines()]
            assert len(training) == previous['completed_episodes']
            start = len(training)
        else:
            state = self.out/'initial.rvp'
            initial=getattr(args,'initial_checkpoint',None)
            if initial:
                shutil.copyfile(initial,state)
            else:
                subprocess.run([self.cli,'init',state],check=True,capture_output=True)
            with self.Session(self.binary,state) as initializer:
                if not initial:
                    initializer.execute((XI/'birth.xi').read_text()+'\n'+self.lib)
                else:
                    initializer.execute(self.source(f'load8 r0 {A+1000}\ncmp r0 174\nje connected_model\ndiv r0 0\nlabel connected_model\nqmpsinfo 5000\nqmpsinfo 7000'))
                state = self.out/'checkpoint-00000.rvp'
                initializer.save(state)
            start = 0
        selected = sorted({0,10,30,100,300,1000,3000,10000,args.episodes})
        selected = [e for e in selected if e<=args.episodes and e>=start]
        init_metadata = {'identity':identity, 'physical_quantum_hardware':False,
                         'classical_circuit_simulation':not args.classical,
                         'qubits_per_agent':1000,'total_active_qubits':2000,'register_structure':'one connected 1000-wire MPS per agent','quantum_components_per_agent':1,'nearest_neighbour_connections':999,
                         'effective_quantum_qubits_per_decision':0 if args.classical else 1000 if self.joint_mode=='independent' else 2000,
                         'independent_latent_channels':1000 if args.task=='dense' else 4,
                         'measurement_mode':'analytic Born expectations, not sampled shots',
                         'circuit_parameters_per_agent':1000,'readout_parameters_per_agent':1000,
                         'theta_gradient_coordinates_per_decision':1000,'gradient_method':'exact commutator, dZ/dtheta=-X',
                         'optimizer':'XI SGD' if args.agent=='vqc' else 'XI episodic REINFORCE, EMA baseline, gamma=1',
                         'seed_overlap_checked':True, 'evaluation_size_per_split':args.eval_size,
                         'started_utc':datetime.now(timezone.utc).isoformat(),
                         'platform':platform.platform(),'python':platform.python_version()}
        publish_text(self.out/'conditions.json',json.dumps(init_metadata,indent=2)+'\n')
        log_path=self.out/'training.jsonl'
        if not args.resume:
            publish_text(log_path,'')
        with self.Session(self.binary,state) as learner:
            for ep in range(start, args.episodes+1):
                if ep in selected and not any(r['episodes']==ep for r in records):
                    checkpoint = self.out/f'checkpoint-{ep:05d}.rvp'
                    if ep:
                        learner.save(checkpoint)
                    digest = sha(checkpoint)
                    with gzip.GzipFile(filename='',mode='wb',fileobj=(self.out/f'checkpoint-{ep:05d}.rvp.gz').open('wb'),mtime=0) as compressed:
                        compressed.write(checkpoint.read_bytes())
                    t0 = time.perf_counter()
                    role=0 if args.agent=='vqc' else 1
                    register_events,_=learner.execute(self.source(f'qmpsinfo {5000 if role==0 else 7000}'))
                    register=next(x for x in register_events if x['type']=='mps_register')
                    item = {'episodes':ep,'checkpoint':checkpoint.name,'checkpoint_sha256':digest,
                            'model':self.model_state(learner), 'usage':learner.metrics(), 'connected_register':register,
                            'iid':self.evaluate(checkpoint), 'ood':self.evaluate(checkpoint,'ood')}
                    if self.joint_mode!='independent':
                        self.args.agent='vqc'
                        item['representation_model']=self.model_state(learner)
                        self.args.agent='qrl'
                    if self.args.agent == 'qrl':
                        item['greedy_iid']=self.evaluate(checkpoint,greedy=True)
                        item['greedy_ood']=self.evaluate(checkpoint,'ood',greedy=True)
                    if ep in [0,args.episodes]:
                        item['observations_zeroed']=self.evaluate(checkpoint,ablate=True)
                        if args.agent=='qrl':
                            item['random_policy']=self.evaluate(checkpoint,random=True)
                    item['evaluation_seconds']=time.perf_counter()-t0
                    records.append(item)
                    window = training[-min(len(training),100):]
                    summary = dict(init_metadata,identity=identity,milestones=records,completed_episodes=ep,
                                   latest_checkpoint=checkpoint.name,latest_checkpoint_sha256=digest,
                                   training_total_ms=sum(x['transport_ms'] for x in training),
                                   native_episode_total_ms=sum(x['episode_ms'] for x in training),
                                   native_update_total_ms=sum(x['update_ms'] for x in training),
                                   median_episode_ms=statistics.median(x['episode_ms'] for x in training) if training else None,
                                   p95_episode_ms=percentile([x['episode_ms'] for x in training],.95),
                                   median_update_ms=statistics.median(x['update_ms'] for x in training) if training else None,
                                   training_experiences=sum(x.get('decisions',1) for x in training),
                                   last100_mean_reward=statistics.mean(x['reward'] for x in window) if window and args.agent=='qrl' else None,
                                   last100_success_rate=statistics.mean(x['success'] for x in window) if window and args.agent=='qrl' else None)
                    # Reopen append handles per episode. At a checkpoint publish
                    # the complete in-memory journal before its manifest, so
                    # long-lived descriptors cannot diverge from a replaced file.
                    publish_text(log_path,''.join(json.dumps(row)+'\n' for row in training))
                    publish_text(manifest,json.dumps(summary,indent=2)+'\n')
                    print(json.dumps({'milestone':ep,'agent':args.agent,'task':args.task,'classical':args.classical,
                                      'iid':item['iid'],'ood':item['ood'],'model':item['model']}),flush=True)
                if ep == args.episodes:
                    break
                events, elapsed = learner.execute(self.source(self.stage('train', ep, training=True)))
                row = dict(metrics(events),episode=ep+1,transport_ms=elapsed)
                training.append(row)
                with log_path.open('a') as log:
                    log.write(json.dumps(row)+'\n')
                if (ep+1)%100 == 0:
                    print(json.dumps({'progress':ep+1,'agent':args.agent,'task':args.task,
                                      'recent_episode_ms':statistics.median(x['episode_ms'] for x in training[-100:])}),flush=True)
        persisted=[json.loads(line) for line in log_path.read_text().splitlines()]
        if len(persisted)!=args.episodes or [r['episode'] for r in persisted]!=list(range(1,args.episodes+1)):
            raise RuntimeError('training journal did not persist every completed episode; checkpoints retained for audit')
        return json.loads(manifest.read_text())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--runtime',required=True)
    parser.add_argument('--session-binary')
    parser.add_argument('--step-budget',type=int,default=1000000)
    parser.add_argument('--agent',choices=['vqc','qrl'],required=True)
    parser.add_argument('--task',required=True)
    parser.add_argument('--episodes',type=int,default=10000)
    parser.add_argument('--seed',type=int,default=173)
    parser.add_argument('--eval-size',type=int,default=64)
    parser.add_argument('--classical',action='store_true')
    parser.add_argument('--initial-checkpoint')
    parser.add_argument('--resume',action='store_true')
    parser.add_argument('--output',required=True)
    args=parser.parse_args()
    if args.task not in (TASKS if args.agent=='vqc' else ['line_easy','line_slip']):
        parser.error('task does not match agent')
    if args.episodes<1 or args.eval_size<1:
        parser.error('positive episodes and evaluation size required')
    Experiment(args).run()


if __name__=='__main__':
    main()

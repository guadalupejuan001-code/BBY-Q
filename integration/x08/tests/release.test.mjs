import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {prepare,verifyRelease} from '../prepare.mjs';
import {initialize,transact} from '../../../ai/personal/x08/session.mjs';

const [runtime,destination]=process.argv.slice(2);
if(!destination)throw Error('Usage: release.test.mjs RUNTIME NEW_TEST_DIRECTORY');
fs.mkdirSync(destination,{recursive:true});
const prepared=prepare(path.join(destination,'build'));
assert.equal(verifyRelease().model_sha256,prepared.model_sha256);
assert.throws(()=>prepare(path.join(destination,'build')),/existing builds/);
const session=path.resolve(destination,'session');
initialize(session,prepared.native);
let result=transact(runtime,prepared.native,session,'release-1','traduce al ingles: yo tengo tres coches');
assert.ok(result.ok,result.error?.message);
assert.match(result.response,/I have three cars/);
const replay=transact(runtime,prepared.native,session,'release-1','traduce al ingles: yo tengo tres coches');
assert.equal(replay.replayed,true);
assert.equal(replay.generation,result.generation);
result=transact(runtime,prepared.native,session,'release-2','lee pagina 122');
assert.ok(result.ok,result.error?.message);
assert.match(result.response,/122/);
const broken=path.join(destination,'tampered');fs.mkdirSync(broken);
const release=new URL('../release/',import.meta.url);
for(const name of ['manifest.json','parent.tar.gz','native.tar.gz'])fs.copyFileSync(new URL(name,release),path.join(broken,name));
fs.appendFileSync(path.join(broken,'native.tar.gz'),'changed');
assert.throws(()=>prepare(path.join(destination,'must-not-exist'),broken),/digest mismatch/);
assert.equal(fs.existsSync(path.join(destination,'must-not-exist')),false);
const report={ok:true,checks:10,canonical_release_restored:true,native_translation:true,book_page_122:true,idempotent_retry:true,tampering_rejected:true,existing_destination_preserved:true,android_tested:false};
fs.writeFileSync(path.join(destination,'results.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
